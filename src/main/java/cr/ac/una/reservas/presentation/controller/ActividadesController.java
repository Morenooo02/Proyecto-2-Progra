    private ImageIcon cargarIcono(String ruta, int ancho, int alto) {
        URL url = getClass().getResource(ruta);

        if (url == null) {
            System.err.println("NO SE ENCONTRO: " + ruta);
            return null;
        }

        ImageIcon original = new ImageIcon(url);
        Image imagen = original.getImage().getScaledInstance(
                ancho, alto, Image.SCALE_SMOOTH
        );

        return new ImageIcon(imagen);
    }

    private void cargar() {
        try {
            LocalDate fecha = dateFecha.getDate();

            if (fecha == null) {
                VistaUtil.error(this, "Debe seleccionar una fecha.");
                return;
            }

            Object[][] matriz = service.obtenerMatrizActividades(fecha);

            modelo.setRowCount(0);

            if (matriz != null) {
                for (Object[] fila : matriz) {
                    modelo.addRow(fila);
                }
            }

        } catch (Exception ex) {
            VistaUtil.error(this, "No se pudieron cargar las actividades.");
        }
    }

    private void generarPdf() {
        String elegido = VistaUtil.elegirRutaPdf(this, "actividades.pdf");
        if (elegido == null) {
            return;
        }
        service.exportarPDF("Programacion de actividades", VistaUtil.columnas(modelo),
                VistaUtil.tablaADatos(modelo), elegido);
        VistaUtil.mensaje(this, "PDF generado.");
    }

